"""Generate framework/v6_portal_book.py: portal pairs of the official maps.

    python -m bcsim.portal_book

Keys use navigation.Memory's edge convention: the north edge of cell (x, y) is
y * w + x, the west edge is w * h + y * w + x. The bot only uses a pair after it
has itself seen one end with the same portal id at the same key, so an unknown
or changed map simply falls back to observation-only portals.
"""

from . import official_suite, reconstruct
from .paths import ROOT

OUT = ROOT / "framework" / "v6_portal_book.py"


def pairs(path):
    board = reconstruct.Board(path.read_text(encoding="utf8"))
    w, h, n = board.w, board.h, board.w * board.h
    out = {}
    for pid, ends in board.portals.items():
        keys = sorted(y * w + x + (n if kind == "v" else 0) for kind, (x, y) in ends)
        if len(keys) == 2:
            out[pid] = tuple(keys)
    return (w, h), out


def main():
    book = {}
    lines = ['"""Portal pairs of the official maps, generated by bcsim.portal_book."""', "",
             "# (width, height) -> list of {portal_id: (edge_key, edge_key)}, one per map",
             "BOOK = {"]
    for path in official_suite.official_maps():
        size, found = pairs(path)
        if found:
            book.setdefault(size, []).append((path.stem, found))
    for size, maps in sorted(book.items()):
        lines.append(f"    {size!r}: [")
        for name, found in maps:
            lines.append(f"        {dict(sorted(found.items()))!r},  # {name}")
        lines.append("    ],")
    lines += ["}", ""]
    OUT.write_bytes("\n".join(lines).encode("utf8"))
    print(OUT)
    for size, maps in sorted(book.items()):
        print(size, [(name, len(found)) for name, found in maps])


if __name__ == "__main__":
    main()
