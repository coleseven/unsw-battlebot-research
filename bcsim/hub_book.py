"""Generate framework/v6_hub_book.py: pearl hubs of the official maps.

    python -m bcsim.hub_book

For each official map: its static layout for in-game identification (a hex
bitset over navigation.Memory edge keys, set where the edge is kelp or a
portal) and up to MAX_HUBS hub cells. A cell's
productivity is the expected pearls per round of the spawn tiles within
Chebyshev distance RADIUS (a tile with gaps [lo, hi] spawns about every
(lo + hi) / 2 rounds). Hubs are greedy local peaks at least SEPARATION apart
and worth at least MIN_SHARE of the best one and HUB_RATIO times the map's
mean productivity (uniform maps get no hubs); values are normalised to 1.
"""

from . import reconstruct
from .official_suite import official_maps
from .paths import ROOT

OUT = ROOT / "framework" / "v6_hub_book.py"
RADIUS, SEPARATION, MAX_HUBS, MIN_SHARE, HUB_RATIO = 2, 5, 12, 0.25, 2.0


def tiles(path):
    w = h = 0
    gaps = {}
    for line in path.read_text(encoding="utf8").splitlines():
        q = line.split()
        if q and q[0] == "MAP":
            w, h = int(q[1]), int(q[2])
        elif q and q[0] == "TILE" and len(q) >= 5 and int(q[4]) > 0:
            gaps[(int(q[1]), int(q[2]))] = (int(q[3]), int(q[4]))
    return w, h, gaps


def cheb(a, b, w, h):
    dx, dy = abs(a[0] - b[0]), abs(a[1] - b[1])
    return max(min(dx, w - dx), min(dy, h - dy))


def hubs(w, h, gaps):
    rate = {t: 2.0 / max(1, lo + hi) for t, (lo, hi) in gaps.items()}
    prod = {}
    for y in range(h):
        for x in range(w):
            total = 0.0
            for dy in range(-RADIUS, RADIUS + 1):
                for dx in range(-RADIUS, RADIUS + 1):
                    total += rate.get(((x + dx) % w, (y + dy) % h), 0.0)
            prod[(x, y)] = total
    best = max(prod.values(), default=0.0)
    mean = sum(prod.values()) / max(1, len(prod))
    chosen = []
    for cell, value in sorted(prod.items(), key=lambda kv: (-kv[1], kv[0][1], kv[0][0])):
        if value < MIN_SHARE * best or value < HUB_RATIO * mean or len(chosen) >= MAX_HUBS:
            break
        if all(cheb(cell, c, w, h) >= SEPARATION for c, _ in chosen):
            chosen.append((cell, value))
    return [(y * w + x, round(v / best, 3)) for (x, y), v in chosen]


def main():
    book = {}
    for path in official_maps():
        w, h, gaps = tiles(path)
        board = reconstruct.Board(path.read_text(encoding="utf8"))
        n = w * h
        bits = 0
        for (x, y) in board.hedge:
            bits |= 1 << (y * w + x)
        for (x, y) in board.vedge:
            bits |= 1 << (n + y * w + x)
        book.setdefault((w, h), []).append((path.stem, f"{bits:x}", hubs(w, h, gaps)))
    lines = ['"""Pearl hubs of the official maps, generated by bcsim.hub_book."""', "",
             "# (width, height) -> list of (non-open edge bitset as hex, [(hub_cell, value)])",
             "BOOK = {"]
    for size, maps in sorted(book.items()):
        lines.append(f"    {size!r}: [")
        for name, bits, hub in maps:
            lines.append(f"        ({bits!r},  # {name}")
            lines.append(f"         {hub!r}),")
        lines.append("    ],")
    lines += ["}", ""]
    OUT.write_bytes("\n".join(lines).encode("utf8"))
    print(OUT, OUT.stat().st_size, "bytes")
    for size, maps in sorted(book.items()):
        for name, _, hub in maps:
            print(size, name, len(hub), "hubs", [(c % size[0], c // size[0], v) for c, v in hub[:6]])


if __name__ == "__main__":
    main()
