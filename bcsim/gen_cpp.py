"""Generate the C++ port's data headers from the Python single source.

    python -m bcsim.gen_cpp            # writes cppbot/params.hpp and the books

`core_params.py` stays the one place tunables live; the portal and hub books
are generated by `bcsim.portal_book` / `bcsim.hub_book`. This script mirrors
all three into `cppbot/*.hpp` so the C++ v7 bot never hand-copies a number.

Run it after changing any of those Python sources, then rebuild cppbot.
"""

from __future__ import annotations

import importlib
import sys
from pathlib import Path

from .paths import ROOT

FRAMEWORK = ROOT / "framework"
CPPBOT = ROOT / "cppbot"

BANNER = ("// Generated by bcsim.gen_cpp from {src}. Do not edit by hand;\n"
          "// edit the Python source and re-run `python -m bcsim.gen_cpp`.\n")


def _load(name: str):
    """Import a framework module in isolation (they use bare imports)."""
    if str(FRAMEWORK) not in sys.path:
        sys.path.insert(0, str(FRAMEWORK))
    if name in sys.modules:
        del sys.modules[name]
    return importlib.import_module(name)


def _cpp_number(value) -> tuple[str, str]:
    """Return (c++ type, literal) for a Python bool/int/float."""
    if isinstance(value, bool):
        return "bool", "true" if value else "false"
    if isinstance(value, int):
        return "int", str(value)
    if isinstance(value, float):
        # repr keeps full precision; force a decimal point so it stays double.
        text = repr(value)
        if not any(c in text for c in ".eE"):
            text += ".0"
        return "double", text
    raise TypeError(f"unsupported param type: {type(value)}")


def gen_params() -> str:
    params = _load("core_params")
    lines = [BANNER.format(src="framework/core_params.py"),
             "#pragma once\n", "namespace params {\n"]
    for name in vars(params):
        if not name.isupper():
            continue
        value = getattr(params, name)
        if not isinstance(value, (bool, int, float)):
            continue
        ctype, literal = _cpp_number(value)
        lines.append(f"inline constexpr {ctype} {name} = {literal};")
    lines.append("}  // namespace params\n")
    return "\n".join(lines)


def gen_portal_book() -> str:
    book = _load("v6_portal_book").BOOK
    out = [BANNER.format(src="framework/v6_portal_book.py"),
           "#pragma once", "#include <map>", "#include <utility>",
           "#include <vector>", "",
           "namespace portal_book {", "",
           "struct Pair { int id, a, b; };",
           "// one entry per candidate map of that size; each is a portal list",
           "using Maps = std::vector<std::vector<Pair>>;", "",
           "inline const std::map<std::pair<int, int>, Maps>& book() {",
           "    static const std::map<std::pair<int, int>, Maps> data = {"]
    for (w, h), maps in sorted(book.items()):
        out.append(f"        {{{{{w}, {h}}}, {{")
        for m in maps:
            pairs = ", ".join(f"{{{pid}, {a}, {b}}}" for pid, (a, b) in sorted(m.items()))
            out.append(f"            {{{pairs}}},")
        out.append("        }},")
    out += ["    };", "    return data;", "}", "",
            "}  // namespace portal_book", ""]
    return "\n".join(out)


def gen_hub_book() -> str:
    book = _load("v6_hub_book").BOOK
    out = [BANNER.format(src="framework/v6_hub_book.py"),
           "#pragma once", "#include <map>", "#include <string>",
           "#include <utility>", "#include <vector>", "",
           "namespace hub_book {", "",
           "struct Hub { int cell; double value; };",
           "struct Layout { std::string bits; std::vector<Hub> hubs; };",
           "using Layouts = std::vector<Layout>;", "",
           "inline const std::map<std::pair<int, int>, Layouts>& book() {",
           "    static const std::map<std::pair<int, int>, Layouts> data = {"]
    for (w, h), layouts in sorted(book.items()):
        out.append(f"        {{{{{w}, {h}}}, {{")
        for bits, hubs in layouts:
            hub_lits = ", ".join(f"{{{cell}, {_cpp_number(float(v))[1]}}}" for cell, v in hubs)
            out.append(f'            {{"{bits}", {{{hub_lits}}}}},')
        out.append("        }},")
    out += ["    };", "    return data;", "}", "",
            "}  // namespace hub_book", ""]
    return "\n".join(out)


def gen_model() -> str:
    """Emit the frozen v3 linear action model (weights + bias)."""
    namespace: dict = {}
    exec((ROOT / "versions/v3/action_model.py").read_text(encoding="utf8"), namespace)
    model = namespace["MODEL"]
    if model["kind"] != "linear":
        raise ValueError(f"only the linear v3 model is ported, got {model['kind']}")
    weights = ", ".join(_cpp_number(float(w))[1] for w in model["weight"])
    bias = _cpp_number(float(model["bias"]))[1]
    return "\n".join([
        BANNER.format(src="versions/v3/action_model.py"),
        "#pragma once", "#include <array>", "",
        "namespace model {", "",
        f"inline constexpr std::array<double, {len(model['weight'])}> WEIGHT = {{{weights}}};",
        f"inline constexpr double BIAS = {bias};", "",
        "}  // namespace model", ""])


def main() -> None:
    CPPBOT.mkdir(exist_ok=True)
    for name, text in (("params.hpp", gen_params()),
                       ("model.hpp", gen_model()),
                       ("portal_book.hpp", gen_portal_book()),
                       ("hub_book.hpp", gen_hub_book())):
        (CPPBOT / name).write_text(text, encoding="utf8")
        print(f"wrote cppbot/{name}")


if __name__ == "__main__":
    main()
